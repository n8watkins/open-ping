import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

// `wrangler.jsonc` is the public template, so it has no D1 database id (an id
// belongs to one Cloudflare account) and keeps the template's defaults. A real install keeps its own values in the
// gitignored `deploy.local.json` and this script merges them into the
// gitignored `.wrangler.prod.jsonc` before every production command, so the
// two files can never drift apart (`npm run deploy:prod`, `db:migrate:prod`).
//
// deploy.local.json:
//   { "database_id": "<uuid from `wrangler d1 create`>",
//     "vars": { "WAITLIST_ENABLED": "true", "HOME_PAGE": "landing" } }

export const OVERRIDES_PATH = "deploy.local.json";
export const OUTPUT_PATH = ".wrangler.prod.jsonc";

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Copies `text`, passing string literals through untouched and letting `skip`
 * decide how many characters to drop at every other position (0 keeps one).
 */
function outsideStrings(text, skip) {
  let out = "";
  let i = 0;
  while (i < text.length) {
    if (text[i] === '"') {
      let j = i + 1;
      while (j < text.length && text[j] !== '"') j += text[j] === "\\" ? 2 : 1;
      out += text.slice(i, j + 1);
      i = j + 1;
      continue;
    }
    const n = skip(text, i);
    if (n > 0) {
      i += n;
    } else {
      out += text[i];
      i++;
    }
  }
  return out;
}

function commentLength(text, i) {
  if (text[i] !== "/") return 0;
  if (text[i + 1] === "/") {
    const end = text.indexOf("\n", i);
    return (end === -1 ? text.length : end) - i;
  }
  if (text[i + 1] === "*") {
    const end = text.indexOf("*/", i + 2);
    return (end === -1 ? text.length : end + 2) - i;
  }
  return 0;
}

function trailingCommaLength(text, i) {
  return text[i] === "," && /^\s*[}\]]/.test(text.slice(i + 1)) ? 1 : 0;
}

/** Parses JSONC: JSON plus `//` and block comments and trailing commas. */
export function parseJsonc(text) {
  const noComments = outsideStrings(text, commentLength);
  return JSON.parse(outsideStrings(noComments, trailingCommaLength));
}

/** Returns the production config: the template with the local overrides applied. */
export function buildProdConfig(template, overrides) {
  const id = overrides?.database_id;
  if (typeof id !== "string" || !UUID.test(id)) {
    throw new Error(`${OVERRIDES_PATH}: "database_id" must be your D1 database's uuid`);
  }
  const vars = overrides.vars ?? {};
  for (const [key, value] of Object.entries(vars)) {
    if (!(key in (template.vars ?? {}))) {
      throw new Error(`${OVERRIDES_PATH}: unknown var "${key}" (not in wrangler.jsonc)`);
    }
    if (typeof value !== "string") {
      throw new Error(`${OVERRIDES_PATH}: var "${key}" must be a string`);
    }
  }
  const dbs = template.d1_databases ?? [];
  if (!dbs.some((db) => db.binding === "DB")) {
    throw new Error('wrangler.jsonc: expected a D1 database bound as "DB"');
  }
  if (dbs.some((db) => db.database_id)) {
    // A public template must never carry one account's id; it goes in here.
    throw new Error(`wrangler.jsonc: remove the D1 database_id; put it in ${OVERRIDES_PATH}`);
  }
  return {
    ...template,
    vars: { ...template.vars, ...vars },
    d1_databases: dbs.map((db) => (db.binding === "DB" ? { ...db, database_id: id } : db)),
  };
}

function main() {
  if (!existsSync(OVERRIDES_PATH)) {
    console.error(
      `Missing ${OVERRIDES_PATH}. Create it with your D1 database id, for example:\n` +
        `  { "database_id": "<uuid>", "vars": {} }\n` +
        "See docs/INSTALL.md, \"Keep your own ids out of git\".",
    );
    process.exit(1);
  }
  const template = parseJsonc(readFileSync("wrangler.jsonc", "utf8"));
  const overrides = JSON.parse(readFileSync(OVERRIDES_PATH, "utf8"));
  const config = buildProdConfig(template, overrides);
  writeFileSync(
    OUTPUT_PATH,
    `// Generated by scripts/prod-config.mjs from wrangler.jsonc and ${OVERRIDES_PATH}.\n` +
      "// Do not edit or commit; edit those files instead.\n" +
      `${JSON.stringify(config, null, 2)}\n`,
    { mode: 0o600 },
  );
  console.log(`Wrote ${OUTPUT_PATH}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  try {
    main();
  } catch (err) {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  }
}
